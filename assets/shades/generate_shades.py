def antler(s):
    beam = [np.array(p) for p in [(0.04 * s, 2.18, 0.72), (0.24 * s, 2.45, 0.62), (0.40 * s, 2.72, 0.55),
                                  (0.50 * s, 3.00, 0.62)]]
    tube(m, b, beam, [0.035, 0.028, 0.02, 0.006], seg=7, per_segment=4)
    for i, (k, d) in enumerate([(0.15, (0.1 * s, 0.6, 1.0)), (0.45, (0.2 * s, 1.0, 0.6)),
                                (0.7, (0.0, 1.0, 0.1)), (0.85, (0.4 * s, 0.8, -0.3))]):
        p = beam[0] + (beam[-1] - beam[0]) * k + np.array([0.04 * s * math.sin(k * 6), 0, 0])
        dd = np.asarray(d) / np.linalg.norm(d)
        L = 0.22 + 0.06 * i
        tube(m, b, [p, p + dd * L * 0.6 + np.array([0, 0.03, 0]), p + dd * L], [0.02, 0.012, 0.003], seg=6,
             per_segment=2)


