rng = np.random.default_rng(1977)


def write_mtl(name):
    with open(name, 'w') as f:
        f.write('# generated by generate_shades.py\n')
        for n, c in MATS.items():
            f.write(f'newmtl {n}\nKa {c[0]:.3f} {c[1]:.3f} {c[2]:.3f}\nKd {c[0]:.3f} {c[1]:.3f} {c[2]:.3f}\n'
                    f'Ks 0.05 0.05 0.05\nNs 12\nd 1.00\nillum 2\n\n')


def lumpy(amount, seed):
    """A shape for ellipsoid(): the surface goes in and out a little (not smooth: made of something)."""
    a, b, c = 3.0 + seed, 4.0 + 0.7 * seed, 5.0 + 0.3 * seed

    def f(p):
        k = 1.0 + amount * math.sin(a * p[0] + seed) * math.sin(b * p[1] + 2 * seed) * math.sin(c * p[2] + 1)
        return p * k
    return f


def blob(m, mat, centre, radii, amount=0.08, rot=None, nlat=12, nlon=18):
    ellipsoid(m, mat, centre, radii, nlat=nlat, nlon=nlon, rot=rot, shape=lumpy(amount, rng.uniform(0, 3)))


def limb(m, mat, pts, radii, seg=9):
    tube(m, mat, pts, radii, seg=seg, per_segment=4)


def both(f):
    """Calls f(s) for the right (s = -1) and the left (s = +1) side."""
    for s in (-1.0, 1.0):
        f(s)


def wisps(m, mat, anchors, length=(0.3, 0.7), radius=0.025):
    """Tatters of darkness hanging from the anchors, swaying a little."""
    for a in anchors:
        a = np.asarray(a, float)
        L = rng.uniform(*length)
        drift = rng.normal(0, 0.08, 3)
        drift[1] = 0
        pts = [a, a + np.array([0, -0.35 * L, 0]) + 0.4 * drift, a + np.array([0, -0.7 * L, 0]) + drift,
               a + np.array([0, -L, 0]) + 1.4 * drift]
        pts = [np.array([p[0], max(p[1], 0.05), p[2]]) for p in pts]
        r = radius * rng.uniform(0.7, 1.3)
        tube(m, mat, pts, [r, 0.75 * r, 0.4 * r, 0.05 * r], seg=6, per_segment=3)


def spikes(m, mat, base_pts, up=(0, 1, 0), length=0.12, radius=0.03):
    for p in base_pts:
        p = np.asarray(p, float)
        d = np.asarray(up, float) + rng.normal(0, 0.25, 3)
        d = d / np.linalg.norm(d)
        L = length * rng.uniform(0.7, 1.3)
        tube(m, mat, [p, p + d * L * 0.5, p + d * L], [radius, radius * 0.5, radius * 0.05], seg=6, per_segment=2)


