# -------------------------------------------------------------------------- wings
def wing_outline(n=40):
    """The left wing's outline in its plane (x out from the hinge, z forward): a long narrow
    blade, the leading edge straight and sweeping back, the trailing edge rounded."""
    pts = []
    for i in range(n + 1):  # the leading edge, root to tip
        x = WING_SPAN * i / n
        pts.append((x, 0.05 - 0.17 * (x / WING_SPAN) ** 1.5))
    for i in range(1, n):  # round the tip and back along the trailing edge
        x = WING_SPAN * (1 - i / n)
        f = x / WING_SPAN
        width = WING_CHORD * math.sqrt(max(0.0, 1 - f ** 2.2)) * (0.35 + 0.65 * min(1.0, f * 4))
        pts.append((x, 0.05 - 0.17 * f ** 1.5 - width - 0.02))
    return pts


def make_wing(sign):
    mesh = Mesh()
    outline = wing_outline()
    centre = np.mean(np.array(outline), axis=0)
    V = [np.array([sign * x, 0.0, z]) for x, z in outline] + [np.array([sign * centre[0], 0.0, centre[1]])]
    N = [np.array([0.0, 1.0, 0.0])] * len(V)
    c = len(V) - 1
    F = [[i, (i + 1) % c, c] for i in range(c)]
    mesh.add('wing', V, N, F)
    # the veins: the leading edge and four that fan out from the root
    lead = [(sign * x, 0.004, z) for x, z in outline[:41:10]]
    tube(mesh, 'vein', lead, [0.012, 0.010, 0.008, 0.006, 0.004], seg=5, per_segment=4)
    for k, (tip_x, tip_dz) in enumerate([(1.45, -0.10), (1.20, -0.22), (0.95, -0.28), (0.65, -0.26)]):
        f = tip_x / WING_SPAN
        z_tip = 0.05 - 0.17 * f ** 1.5 + tip_dz
        tube(mesh, 'vein', [(sign * 0.04, 0.004, 0.0), (sign * tip_x * 0.5, 0.004, z_tip * 0.5 - 0.03 * k),
                            (sign * tip_x, 0.004, z_tip)], [0.007, 0.005, 0.003], seg=4, per_segment=4)
    return mesh


