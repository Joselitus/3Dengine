body = Mesh()

# The thorax: a hunched oval, higher at the back of the head
ellipsoid(body, 'body', (0, 0.02, 0.02), (0.30, 0.33, 0.42), nlat=14, nlon=20, rot=rot_x(math.pi / 2),
          shape=lambda p: p * np.array([1.0, 1.0, 1.0 + 0.18 * max(0.0, p[1])]))
# its white marks on the back (a line down the middle and two at the sides)
ellipsoid(body, 'stripe', (0, 0.30, 0.10), (0.035, 0.07, 0.30), rot=rot_x(math.pi / 2 - 0.35))
for s in (1, -1):
    ellipsoid(body, 'stripe', (0.17 * s, 0.23, 0.18), (0.05, 0.05, 0.11), rot=rot_x(math.pi / 2 - 0.5))
    ellipsoid(body, 'stripe', (0.23 * s, 0.05, -0.12), (0.06, 0.12, 0.05))

# The head: low in front of the thorax, almost all eyes
ellipsoid(body, 'body', (0, -0.10, 0.50), (0.17, 0.17, 0.16), nlat=10, nlon=16)
for s in (1, -1):
    ellipsoid(body, 'eye', (0.105 * s, -0.07, 0.55), (0.10, 0.15, 0.12), nlat=10, nlon=14)
# the proboscis, long and thin, curving down; the palps beside it
tube(body, 'proboscis', [(0, -0.20, 0.62), (0, -0.33, 0.95), (0, -0.55, 1.30), (0, -0.82, 1.58),
                         (0, -1.05, 1.70)], [0.035, 0.028, 0.022, 0.016, 0.006], seg=8)
for s in (1, -1):
    tube(body, 'body', [(0.04 * s, -0.19, 0.62), (0.07 * s, -0.30, 0.82), (0.08 * s, -0.44, 0.95)],
         [0.022, 0.018, 0.012], seg=6)
    ellipsoid(body, 'stripe', (0.08 * s, -0.44, 0.95), (0.018, 0.018, 0.018), nlat=4, nlon=6)
# feathery antennae: a stalk with whorls of hairs
for s in (1, -1):
    stalk = tube(body, 'body', [(0.05 * s, 0.0, 0.63), (0.13 * s, 0.14, 0.86), (0.22 * s, 0.30, 1.05)],
                 [0.014, 0.010, 0.005], seg=6, per_segment=6)
    for k in range(2, len(stalk) - 1, 2):
        p = stalk[k]
        t = unit(stalk[k + 1] - stalk[k - 1])
        u = unit(np.cross(t, [0, 1, 0]))
        w = np.cross(t, u)
        length = 0.10 * (1.0 - k / len(stalk)) + 0.03
        for i in range(6):
            a = 2 * math.pi * i / 6 + k
            d = math.cos(a) * u + math.sin(a) * w
            tube(body, 'body', [p, p + d * length], [0.004, 0.002], seg=4, per_segment=1)

# The abdomen: 8 segments down a curve that sags behind the thorax, each with a white band at
# its front and a dark red underside. A model of its own (mosquito_abdomen.obj, in the body's
# frame), so that the engine can swell it when it fills with fuel: about ABDOMEN_PIVOT, where it
# joins the thorax (Mosquito.cpp has the same numbers)
ABDOMEN_PIVOT = (0.0, -0.05, -0.30)
abdomen = Mesh()
spine = catmull([(0, -0.05, -0.30), (0, -0.16, -0.80), (0, -0.30, -1.30), (0, -0.40, -1.72)], 8)
seg_count = 8
for k in range(seg_count):
    t0, t1 = k / seg_count, (k + 1) / seg_count
    a = spine[int(t0 * (len(spine) - 1))]
    b = spine[int(t1 * (len(spine) - 1))]
    mid = (a + b) / 2
    length = np.linalg.norm(b - a)
    r = 0.25 * (1.0 - 0.62 * ((k + 0.5) / seg_count) ** 1.4)
    rot = along(b - a)
    ellipsoid(abdomen, 'body', mid, (r, length * 0.62, r * 0.88), nlat=8, nlon=16, rot=rot)
    ellipsoid(abdomen, 'belly', mid - rot @ np.array([0, 0, r * 0.25]), (r * 0.9, length * 0.55, r * 0.70),
              nlat=8, nlon=14, rot=rot)
    ellipsoid(abdomen, 'stripe', a + (b - a) * 0.12, (r * 1.02, length * 0.12, r * 0.90), nlat=6, nlon=16,
              rot=rot)

# Six long legs (left side; the right side mirrors them): from the underside of the thorax up
# to a high "knee", then down and out. Each leg is 4 straight segments between its 5 joints, and
# each segment is a model of its own (mosquito_leg_<L|R><pair>_<segment>.obj, at its place in the
# body's frame), so that the engine can move them (Mosquito.cpp, LEG_JOINTS: the same numbers).
# White bands at the joints and the feet; the body only has a socket where each leg starts.
LEGS = [  # joints (hip, ..., foot), radii
    ([(0.12, -0.22, 0.20), (0.40, -0.10, 0.52), (0.72, -0.55, 0.95), (0.82, -1.20, 1.22), (0.88, -1.68, 1.35)],
     [0.050, 0.040, 0.030, 0.020, 0.009]),
    ([(0.15, -0.26, 0.00), (0.62, 0.02, 0.05), (1.12, -0.52, 0.00), (1.32, -1.22, -0.10), (1.42, -1.70, -0.14)],
     [0.052, 0.042, 0.030, 0.020, 0.009]),
    ([(0.12, -0.22, -0.20), (0.48, 0.02, -0.52), (0.80, -0.30, -1.08), (0.90, 0.08, -1.58), (0.84, 0.52, -1.90)],
     [0.050, 0.040, 0.030, 0.020, 0.009]),
]
leg_meshes = {}
for pair, (points, radii) in enumerate(LEGS):
    for side_name, side in (('L', points), ('R', mirror(points))):
        ellipsoid(body, 'body', side[0], (0.07, 0.07, 0.07), nlat=6, nlon=10)  # the socket
        for k in range(4):
            mesh = Mesh()
            a, b = np.array(side[k], float), np.array(side[k + 1], float)
            tube(mesh, 'body', [a, b], [radii[k], radii[k + 1]], seg=8, per_segment=1)
            if k > 0:  # the white band of the joint it starts at
                ellipsoid(mesh, 'stripe', a, (radii[k] * 1.25, 0.045, radii[k] * 1.25), nlat=5, nlon=8,
                          rot=along(b - a))
            if k == 3:
                ellipsoid(mesh, 'stripe', b, (0.016, 0.016, 0.016), nlat=4, nlon=6)
            leg_meshes[f'mosquito_leg_{side_name}{pair}_{k}.obj'] = mesh

# The halteres: little knobbed stalks behind the wings
for s in (1, -1):
    tube(body, 'body', [(0.16 * s, 0.18, -0.22), (0.26 * s, 0.22, -0.30)], [0.012, 0.008], seg=5,
         per_segment=1)
    ellipsoid(body, 'stripe', (0.27 * s, 0.22, -0.31), (0.03, 0.03, 0.03), nlat=5, nlon=8)

